"""California Proposition 99: SyntheticControl scored against Abadie et al.'s
published synthetic control result. See tests/fixtures/real_data/prop99.md."""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest
from cp_causal.registry import get_estimator
from cp_core.dataset import CausalDataset, CausalSchema
from cp_core.values import EstimatorConfig

FIXTURE = Path(__file__).parent.parent / "fixtures" / "real_data" / "prop99.csv"


def _dataset() -> CausalDataset:
    frame = pd.read_csv(FIXTURE)
    schema = CausalSchema(
        unit="state",
        treatment="treatment",
        outcome="cigsale",
        covariates=(),
        outcome_type="continuous",
        time="year",
    )
    return CausalDataset(frame=frame, schema=schema)


# Measured 2026-09-04, after the donor-solve conditioning fix (commit fd9e944); CI re-measured
# 2026-09-28 after the CI/donor_contamination_check hull-aware fix (design doc
# 2026-09-28-synthetic-control-ci-calibration.md) -- point, p-value and the year-2000 gap are
# unchanged (California's own fit passes its own convex-hull check, so `point` never used the
# ridge fallback either before or after), only the CI moved:
#
#   average post-treatment gap (this is `point`)   -19.5136
#   permutation CI, pre-fix                        (-36.5439, -2.4833)
#   permutation CI, post-fix                       (-45.3312, 6.3039)
#   permutation p-value                             0.0769  (= 3/39)
#   year-2000 gap                                 -26.5966
#   pre-treatment RMSE                              1.66
#
# The CI widened because the hull-aware reference distribution now includes one placebo donor
# (of 38) whose own convex-hull check fails and whose ridge-augmented placebo estimate is a
# large outlier (-27.8, against a simplex placebo estimate of 0.3 for the same donor) -- at 38
# donors, a 95th-percentile quantile is dominated by its top one or two values, so this single
# donor's ridge fit moves the whole interval. Verified directly, not assumed: recomputing the
# CI by hand from `hull_aware_placebo_runs` reproduces this exactly, and the donor's ridge fit
# itself is numerically unremarkable (finite intercept and coefficients, no NaN/overflow) --
# this is the estimator's genuine, if outlier-sensitive, hull-aware uncertainty, not a bug in
# the fix. See `test_consumption_fell_rather_than_rose` for what this means for that test.
#
# Abadie, Diamond & Hainmueller (2010), "Synthetic Control Methods for
# Comparative Case Studies: Estimating the Effect of California's Tobacco
# Control Program", JASA 105(490):493-505. Read directly rather than recalled;
# the figures below are quoted from §3.3 (p. 500) and Table 2 (p. 500):
#
#   "for the entire 1989-2000 period cigarette consumption was reduced by an
#    average of almost 20 packs per capita, a decline of approximately 25%"
#   and, from the abstract, sales by 2000 about 26 packs below the
#   counterfactual.
#
# `SyntheticControl.fit` reports `point` as the mean of
# `treated - synthetic` over the post-treatment periods, so it is directly
# comparable to the first of those.
#
# This is external validation, not a self-consistency check: nothing about
# this panel was generated by code in this repository. It is also not an exact
# replication and is not asserted as one. Abadie et al. nest a second
# optimisation over predictor importance and use lnincome, beer, age15to24,
# retprice and three lagged sales years; this implementation deliberately uses
# the pre-treatment outcome path alone (design doc §5.1). That the two land
# within half a pack of each other is the finding.
ABADIE_AVERAGE_GAP = -20.0
ABADIE_YEAR_2000_GAP = -26.0
MEASURED_POINT = -19.5136
MEASURED_YEAR_2000_GAP = -26.5966


def test_the_average_post_treatment_gap_matches_abadies_published_figure():
    estimate = get_estimator("synthetic_control")().fit(_dataset(), EstimatorConfig(random_seed=0))

    # 5 packs is a quarter of the effect itself, and comfortably wider than
    # the 0.49 currently separating this fit from the published figure -- the
    # band is for a specification difference, not for solver noise.
    assert estimate.point == pytest.approx(ABADIE_AVERAGE_GAP, abs=5.0)
    assert estimate.point == pytest.approx(MEASURED_POINT, abs=0.5)


def test_consumption_fell_rather_than_rose():
    # An identity check independent of any tolerance: whatever the magnitude,
    # Proposition 99 cannot have raised cigarette sales.
    #
    # This asserts the point estimate's sign only, not the CI's. It asserted `ci.upper < 0.0`
    # too until the hull-aware CI fix (design doc 2026-09-28-synthetic-control-ci-calibration.md):
    # that additional assertion was never actually implied by the test's own stated intent above
    # -- "the true effect cannot be positive" is a substantive, independently-known fact about
    # Proposition 99, not a claim that any one sample's 95% CI must exclude non-negative values,
    # and a valid CI is not required to exclude a wrong-signed region just because the sign is
    # known by other means. It happened to hold under the pre-fix CI and stopped holding under
    # the corrected one (see the file-level comment above for why, verified directly rather than
    # assumed) -- dropped rather than kept as a coincidental byproduct of the defect this phase
    # fixed.
    estimate = get_estimator("synthetic_control")().fit(_dataset(), EstimatorConfig(random_seed=0))

    assert estimate.point < 0.0


def test_the_effect_grows_over_the_post_treatment_period():
    """Abadie et al.'s Figure 3 shows the gap widening year on year.

    Asserted because it is the shape of the result, and a fit that recovered
    the right average with the wrong trajectory would be wrong in a way the
    point estimate alone cannot see.
    """
    estimate = get_estimator("synthetic_control")().fit(_dataset(), EstimatorConfig(random_seed=0))
    pointwise = np.asarray(estimate.counterfactual.pointwise_effect)

    assert pointwise[-1] == pytest.approx(MEASURED_YEAR_2000_GAP, abs=1.0)
    assert pointwise[-1] == pytest.approx(ABADIE_YEAR_2000_GAP, abs=5.0)
    assert pointwise[-1] < estimate.point  # the final year is worse than the average


def test_the_synthetic_control_tracks_california_before_the_law():
    """A post-period gap only means anything if the pre-period gap does not.

    This is the check that would have caught the conditioning defect fixed in
    fd9e944: the unconverged fit had a pre-treatment RMSE of 16.0 against a
    post-period effect of 41.7, so more than a third of its "effect" was
    simply failure to match California before 1989.
    """
    estimate = get_estimator("synthetic_control")().fit(_dataset(), EstimatorConfig(random_seed=0))
    fit_check = {check.name: check for check in estimate.assumptions}["pre_treatment_fit"]

    assert fit_check.status == "PASS"
    assert fit_check.statistic < 3.0  # measured 1.66; the broken fit gave 16.0
